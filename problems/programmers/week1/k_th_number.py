def solution(array, commands):
    answer = []
    
    for i in commands: # i = [2,5,3], [4,4,1], [1,7,3], i는 리스트임
        temp = []
        temp = sorted(array[i[0]-1:i[1]]) 
        # 문제에서는 1번째부터 세고, 파이썬에서는 0번째부터 세므로 "문제-1"번째부터 세도록 해야 함.
        # 파이썬에서는 [n:m] -> n부터 m-1까지를 뜻함 -> m까지 세려면 m+1을 해야 함
        # -> 문제에서 n~m번째를 원했는데 이는 파이썬에서 n-1 ~ m-1번째까지임. 
        # -> [n-1:m]으로 세어야 n-1 ~ m-1이므로 [n-1:m]로 함.
        answer.append(temp[i[2]-1])
    
    return answer

print(solution([1, 5, 2, 6, 3, 7, 4], [[2, 5, 3], [4, 4, 1], [1, 7, 3]]))

